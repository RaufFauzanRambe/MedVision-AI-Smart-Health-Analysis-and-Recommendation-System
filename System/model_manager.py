"""
MedVision-AI :: model_manager.py
================================
The hybrid AI layer.

Two cooperating estimators produce the same output contract
(``probability`` in [0, 1], ``level``, ``method``, interpretable ``factors``):

1. Rule-based points model (always available, zero dependencies)
   A transparent cardiometabolic risk score: clinical findings add weighted
   points (config.RISK_POINTS) which are squashed through a logistic curve.
   Fully interpretable - every contributing factor is reported.

2. scikit-learn RandomForest (optional)
   When sklearn is installed, ``train()`` fits a RandomForest classifier on
   *weak-supervision labels* generated by the rule model (plus deterministic
   jitter augmentation for small datasets). Once trained, predictions
   automatically upgrade to the model; if anything goes wrong the system
   transparently falls back to the rules. This keeps the demo honest: the
   ML model learns to generalize the rule engine's clinical logic, since no
   real labeled outcome data ships with an educational package.

Both paths share the same 17-feature vector, so switching is seamless.
"""

from __future__ import annotations

import math
import pickle
import random
import statistics
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from . import config

__all__ = ["ModelManager"]

try:  # optional dependency - the system must run without it
    import sklearn  # type: ignore
    from sklearn.ensemble import RandomForestClassifier  # type: ignore
    SKLEARN_AVAILABLE = True
except Exception:  # pragma: no cover - depends on environment
    SKLEARN_AVAILABLE = False

FEATURE_NAMES = [
    "age", "sex_male", "bmi", "systolic_bp", "diastolic_bp", "heart_rate",
    "fasting_glucose", "total_cholesterol", "hdl_cholesterol", "ldl_cholesterol",
    "sleep_hours", "steps_k", "smoking", "exercise_per_week",
    "family_hypertension", "family_diabetes", "family_heart_disease",
]


class ModelManager:
    """Trains/serves the optional ML risk model and owns the rule fallback."""

    def __init__(self, model_file: Optional[Path] = None):
        self.model_file = Path(model_file) if model_file else Path(config.MODEL_FILE)
        self.model = None
        self.trained_at: Optional[str] = None
        self.training_samples = 0
        self.logger = config.get_logger("model_manager")
        if SKLEARN_AVAILABLE and self.model_file.exists():
            self.load_model()

    # ------------------------------------------------------------------
    # Feature engineering
    # ------------------------------------------------------------------

    def build_features(self, record: Dict[str, Any],
                       user: Optional[Dict[str, Any]] = None) -> List[float]:
        """Map a (record, user) pair onto the canonical feature vector."""
        user = user or {}
        sex = (user.get("sex") or "other").lower()
        height = record.get("height_cm") or user.get("height_cm")
        weight = record.get("weight_kg")
        bmi = 0.0
        if height and weight:
            meters = float(height) / 100.0
            bmi = float(weight) / (meters * meters)
        fh = user.get("family_history") or {}

        def flag(key: str) -> float:
            return 1.0 if fh.get(key) else 0.0

        return [
            float(user.get("age") or 0),
            1.0 if sex == "male" else 0.0,
            bmi,
            float(record.get("systolic_bp") or 0),
            float(record.get("diastolic_bp") or 0),
            float(record.get("heart_rate") or 0),
            float(record.get("fasting_glucose") or 0),
            float(record.get("total_cholesterol") or 0),
            float(record.get("hdl_cholesterol") or 0),
            float(record.get("ldl_cholesterol") or 0),
            float(record.get("sleep_hours") or 0),
            float(record.get("steps") or 0) / 1000.0,
            1.0 if record.get("smoking") else 0.0,
            float(record.get("exercise_sessions_per_week") or 0),
            flag("hypertension"),
            flag("diabetes"),
            flag("heart_disease"),
        ]

    # ------------------------------------------------------------------
    # Rule-based risk model (always available)
    # ------------------------------------------------------------------

    def rule_based_risk(self, record: Dict[str, Any],
                        user: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Transparent points-based cardiometabolic risk estimate."""
        user = user or {}
        sex = (user.get("sex") or "other").lower()
        age = user.get("age") or 0
        fh = user.get("family_history") or {}
        pts = config.RISK_POINTS
        factors: List[str] = []
        score = 0.0

        # -- blood pressure ------------------------------------------------
        sbp, dbp = record.get("systolic_bp"), record.get("diastolic_bp")
        if sbp is not None and dbp is not None:
            if sbp >= config.BP_CRISIS_SYSTOLIC or dbp >= config.BP_CRISIS_DIASTOLIC:
                score += pts["bp_stage2_or_crisis"]
                factors.append(f"Blood pressure {sbp:g}/{dbp:g} in crisis range")
            elif sbp >= 140 or dbp >= 90:
                score += pts["bp_stage2_or_crisis"]
                factors.append(f"Stage 2 hypertension ({sbp:g}/{dbp:g})")
            elif sbp >= 130 or dbp >= 80:
                score += pts["bp_stage1"]
                factors.append(f"Elevated/stage-1 blood pressure ({sbp:g}/{dbp:g})")
            elif sbp >= 120:
                score += pts["bp_elevated"]
                factors.append(f"Systolic BP above ideal ({sbp:g})")

        # -- glucose ----------------------------------------------------------
        glucose = record.get("fasting_glucose")
        if glucose is not None:
            if glucose >= 126:
                score += pts["glucose_diabetes_range"]
                factors.append(f"Fasting glucose {glucose:g} mg/dL "
                               "(diabetes range)")
            elif glucose >= 100:
                score += pts["glucose_prediabetes"]
                factors.append(f"Fasting glucose {glucose:g} mg/dL "
                               "(prediabetes)")

        # -- lipids --------------------------------------------------------------
        tc = record.get("total_cholesterol")
        ldl = record.get("ldl_cholesterol")
        hdl = record.get("hdl_cholesterol")
        if tc is not None and tc >= 240:
            score += pts["total_cholesterol_high"]
            factors.append(f"Total cholesterol {tc:g} mg/dL (high)")
        if ldl is not None:
            if ldl >= 190:
                score += pts["ldl_very_high"]
                factors.append(f"LDL {ldl:g} mg/dL (very high)")
            elif ldl >= 160:
                score += pts["ldl_high"]
                factors.append(f"LDL {ldl:g} mg/dL (high)")
        hdl_cut = config.CHOLESTEROL["hdl_low_female"] if sex == "female" \
            else config.CHOLESTEROL["hdl_low_male"]
        if hdl is not None and hdl < hdl_cut:
            score += pts["hdl_low"]
            factors.append(f"Low HDL {hdl:g} mg/dL")

        # -- BMI ----------------------------------------------------------------
        height = record.get("height_cm") or user.get("height_cm")
        weight = record.get("weight_kg")
        if height and weight:
            bmi = float(weight) / (float(height) / 100.0) ** 2
            if bmi >= 30:
                score += pts["obese"]
                factors.append(f"Obesity (BMI {bmi:.1f})")
            elif bmi >= 25:
                score += pts["overweight"]
                factors.append(f"Overweight (BMI {bmi:.1f})")

        # -- lifestyle -------------------------------------------------------------
        if record.get("smoking"):
            score += pts["current_smoker"]
            factors.append("Current smoker")
        steps = record.get("steps")
        ex = record.get("exercise_sessions_per_week")
        if steps is not None and ex is not None and \
                steps < config.ACTIVITY["steps_sedentary"] and ex < 2:
            score += pts["sedentary"]
            factors.append(f"Sedentary lifestyle ({steps:g} steps, "
                           f"{ex:g} workouts/week)")
        sleep_h = record.get("sleep_hours")
        if sleep_h is not None and sleep_h < 6:
            score += pts["sleep_deprived"]
            factors.append(f"Chronic short sleep ({sleep_h:g} h/night)")

        # -- demographics & family history --------------------------------------
        if sex == "male" and age > 45:
            score += pts["age_male_over_45"]
            factors.append(f"Age {age:g} (male, > 45)")
        elif sex == "female" and age > 55:
            score += pts["age_female_over_55"]
            factors.append(f"Age {age:g} (female, > 55)")
        fam_count = sum(1 for cond in ("hypertension", "diabetes", "heart_disease")
                        if fh.get(cond))
        if fam_count:
            score += pts["family_history_each"] * fam_count
            conds = [c.replace("_", " ") for c in
                     ("hypertension", "diabetes", "heart_disease") if fh.get(c)]
            factors.append("Family history: " + ", ".join(conds))

        probability = self._points_to_probability(score)
        return {
            "probability": probability,
            "level": self._level(probability),
            "points": round(score, 2),
            "factors": factors,
            "method": "rule_based_points_model",
        }

    @staticmethod
    def _points_to_probability(points: float) -> float:
        p = 1.0 / (1.0 + math.exp(-config.RISK_SLOPE * (points - config.RISK_CENTER)))
        return round(max(config.RISK_PROB_FLOOR,
                         min(config.RISK_PROB_CEIL, p)), 3)

    @staticmethod
    def _level(probability: float) -> str:
        for upper, label in config.RISK_LEVELS:
            if probability < upper:
                return label
        return "Very High"

    # ------------------------------------------------------------------
    # Optional ML path (scikit-learn)
    # ------------------------------------------------------------------

    def train(self, pairs: Sequence[Tuple[Dict[str, Any], Dict[str, Any]]],
              augment: int = 12, random_seed: int = 42) -> Dict[str, Any]:
        """Fit the RandomForest on weak-supervision labels from the rule model.

        Args:
            pairs: iterable of (record, user) dicts.
            augment: jittered synthetic copies generated per real sample
                (small-data augmentation; set 0 to disable).
            random_seed: deterministic RNG seed for reproducibility.

        Returns:
            Metrics dict: {"trained", "method", "samples", "accuracy", ...}
        """
        if not SKLEARN_AVAILABLE:
            return {"trained": False,
                    "reason": "scikit-learn is not installed; the rule-based "
                              "risk model remains active."}
        if not pairs:
            return {"trained": False, "reason": "no training data provided"}

        rng = random.Random(random_seed)
        X: List[List[float]] = []
        y: List[int] = []
        jitter_fields = ["systolic_bp", "diastolic_bp", "heart_rate",
                         "fasting_glucose", "total_cholesterol",
                         "hdl_cholesterol", "ldl_cholesterol", "sleep_hours",
                         "steps", "exercise_sessions_per_week", "weight_kg"]

        for record, user in pairs:
            variants: List[Dict[str, Any]] = [dict(record)]
            for _ in range(max(0, augment)):
                variant = dict(record)
                for field in jitter_fields:
                    if variant.get(field) is not None:
                        noise = rng.uniform(-0.06, 0.06)
                        base = float(variant[field])
                        if field == "steps":
                            variant[field] = max(0, int(base * (1 + noise)))
                        elif field in ("exercise_sessions_per_week",):
                            variant[field] = max(0, int(round(base + (1 if noise > 0.04 else (-1 if noise < -0.04 else 0)))))
                        else:
                            variant[field] = round(base * (1 + noise), 2)
                if record.get("smoking") is not None and rng.random() < 0.08:
                    variant["smoking"] = not record["smoking"]
                variants.append(variant)

            for variant in variants:
                label = int(self.rule_based_risk(variant, user)["probability"] >= 0.5)
                X.append(self.build_features(variant, user))
                y.append(label)

        model = RandomForestClassifier(
            n_estimators=200, max_depth=8, random_state=random_seed,
            class_weight="balanced",
        )
        model.fit(X, y)

        train_acc = model.score(X, y)
        self.model = model
        self.training_samples = len(X)
        self.trained_at = __import__("datetime").datetime.now().isoformat(
            timespec="seconds"
        )
        self.save_model()
        self.logger.info("Trained RandomForest on %d samples "
                         "(weak-supervision labels from rule model).", len(X))
        return {
            "trained": True,
            "method": "sklearn_random_forest",
            "real_samples": len(pairs),
            "total_samples": len(X),
            "augment_factor": augment,
            "train_accuracy": round(train_acc, 3),
            "class_balance": round(statistics.mean(y), 3),
            "note": "Labels are generated by the clinical rule engine "
                    "(weak supervision), so accuracy measures agreement with "
                    "the rules, not real-world outcomes.",
        }

    def predict_risk(self, record: Dict[str, Any],
                     user: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Hybrid prediction: blends the ML model with the rule model.

        When a trained model is available the final probability is a 50/50
        blend of the RandomForest output and the transparent rule-based
        probability. Anchoring to the clinical rules prevents the small-data
        model from producing overconfident outliers, while still letting it
        sharpen (or smooth) the estimate. Falls back to pure rules if the
        model is missing or fails.
        """
        base = self.rule_based_risk(record, user)
        if SKLEARN_AVAILABLE and self.model is not None:
            try:
                features = [self.build_features(record, user)]
                model_prob = float(self.model.predict_proba(features)[0][1])
                blended = round(0.5 * base["probability"] + 0.5 * model_prob, 3)
                return {
                    "probability": blended,
                    "level": self._level(blended),
                    "factors": base["factors"],   # keep interpretability
                    "method": "hybrid_rule+random_forest",
                    "rule_probability": base["probability"],
                    "model_probability": round(model_prob, 3),
                }
            except Exception as exc:  # any model failure -> graceful fallback
                self.logger.warning("Model prediction failed (%s); "
                                    "falling back to rules.", exc)
        return base

    # ------------------------------------------------------------------
    # Persistence & status
    # ------------------------------------------------------------------

    def save_model(self) -> bool:
        if self.model is None:
            return False
        self.model_file.parent.mkdir(parents=True, exist_ok=True)
        with open(self.model_file, "wb") as fh:
            pickle.dump(
                {"model": self.model, "trained_at": self.trained_at,
                 "training_samples": self.training_samples,
                 "feature_names": FEATURE_NAMES},
                fh,
            )
        return True

    def load_model(self) -> bool:
        try:
            with open(self.model_file, "rb") as fh:
                blob = pickle.load(fh)
            self.model = blob["model"]
            self.trained_at = blob.get("trained_at")
            self.training_samples = blob.get("training_samples", 0)
            return True
        except Exception as exc:
            self.logger.warning("Could not load model artifact (%s); "
                                "staying on rule-based mode.", exc)
            self.model = None
            return False

    def get_status(self) -> Dict[str, Any]:
        return {
            "sklearn_available": SKLEARN_AVAILABLE,
            "model_trained": self.model is not None,
            "trained_at": self.trained_at,
            "training_samples": self.training_samples,
            "active_method": ("hybrid_rule+random_forest"
                              if SKLEARN_AVAILABLE and self.model is not None
                              else "rule_based_points_model"),
            "model_file": str(self.model_file) if self.model_file.exists() else None,
        }
